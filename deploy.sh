#!/bin/bash

# ====================================================================
# 리눅스 assetManage Git 자동 최신 소스 배포 스크립트 (deploy.sh)
# ====================================================================
# - Git 최신 변경 사항 pull
# - Docker Compose 컨테이너 무중단 재빌드 및 재실행
# - 임시 도커 이미지 자동 정리

set -e

echo "===================================================="
echo "🚀 [1/3] Git 최신 소스 코드를 당겨오는 중 (git pull)..."
echo "===================================================="
git pull origin main || git pull origin master

echo ""
echo "===================================================="
echo "🐳 [2/3] 도커 이미지 재빌드 및 무중단 서버 갱신 중..."
echo "===================================================="
docker compose up -d --build

echo ""
echo "===================================================="
echo "🧹 [3/3] 미사용 구버전 도커 이미지 자동 정리 중..."
echo "===================================================="
docker image prune -f

echo ""
echo "===================================================="
echo "✅ 자산 관리 시스템 최신 버전 배포가 성공적으로 완료되었습니다!"
echo "===================================================="
